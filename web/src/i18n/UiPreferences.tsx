export interface UiPreferencesValue {
  language: LanguagePreference;
  locale: UiLocale;
  theme: UiTheme;
  setLanguage(value: LanguagePreference): void;
  setTheme(value: UiTheme): void;
  t(key: MessageKey, variables?: Variables): string;
}

const defaultValue: UiPreferencesValue = {
  language: 'en', locale: 'en', theme: 'dark',
  setLanguage: () => undefined,
  setTheme: () => undefined,
  t: (key, variables) => interpolate(en[key], variables),
};

const UiPreferencesContext = createContext<UiPreferencesValue>(defaultValue);

export function UiPreferencesProvider({ children }: { children: ReactNode }) {
  const [preferences, setPreferences] = useState(loadUiPreferences);
  const locale = resolveLocale(preferences.language);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dataset.theme = preferences.theme;
    try { localStorage.setItem(STORAGE_KEY, JSON.stringify(preferences)); } catch { /* Persistence is optional. */ }
  }, [locale, preferences]);

  const value = useMemo<UiPreferencesValue>(() => ({
    ...preferences,
    locale,
    setLanguage: (language) => setPreferences((current) => ({ ...current, language })),
    setTheme: (theme) => setPreferences((current) => ({ ...current, theme })),
    t: (key, variables) => interpolate((locale === 'zh-TW' ? zhTW : en)[key], variables),
  }), [locale, preferences]);

  return <UiPreferencesContext.Provider value={value}>{children}</UiPreferencesContext.Provider>;
}

export function useUiPreferences(): UiPreferencesValue {
  return useContext(UiPreferencesContext);
}

