#!/usr/bin/env node

import { readFileSync } from 'node:fs'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const DEFAULT_NODE_VERSION = '24.18.0'
const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..')
const outFile = join(repoRoot, 'runtime-catalog.json')

const PLATFORMS = [
  { key: 'darwin-arm64', nodePlatform: 'darwin', nodeArch: 'arm64', archiveExt: 'tar.gz', exePath: 'bin/node' },
  { key: 'darwin-x64', nodePlatform: 'darwin', nodeArch: 'x64', archiveExt: 'tar.gz', exePath: 'bin/node' },
  { key: 'linux-arm64', nodePlatform: 'linux', nodeArch: 'arm64', archiveExt: 'tar.xz', exePath: 'bin/node' },
  { key: 'linux-x64', nodePlatform: 'linux', nodeArch: 'x64', archiveExt: 'tar.xz', exePath: 'bin/node' },
  { key: 'win32-arm64', nodePlatform: 'win', nodeArch: 'arm64', archiveExt: 'zip', exePath: 'node.exe' },
  { key: 'win32-x64', nodePlatform: 'win', nodeArch: 'x64', archiveExt: 'zip', exePath: 'node.exe' },
]

async function fetchJson(url) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`GET ${url} -> HTTP ${response.status}`)
  return response.json()
}

async function fetchText(url) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`GET ${url} -> HTTP ${response.status}`)
  return response.text()
}

function installedVersion(packageName) {
  const manifest = join(repoRoot, 'node_modules', ...packageName.split('/'), 'package.json')
  const metadata = JSON.parse(readFileSync(manifest, 'utf8'))
  if (!metadata.version) {
    throw new Error(`could not read installed version for ${packageName} at ${manifest}`)
  }
  return metadata.version
}

function expectedVersions() {
  return {
    claude: installedVersion('@anthropic-ai/claude-agent-sdk'),
    codex: installedVersion('@openai/codex'),
    node: DEFAULT_NODE_VERSION,
  }
}

async function buildClaudeSection(version) {
  const platforms = {}
  for (const { key } of PLATFORMS) {
    const packageName = `claude-agent-sdk-${key}`
    const metadata = await fetchJson(`https://registry.npmjs.org/@anthropic-ai/${packageName}`)
    const entry = metadata.versions?.[version]
    if (!entry) throw new Error(`@anthropic-ai/${packageName}@${version} not found on npm`)
    platforms[key] = { packageName, integrity: entry.dist.integrity }
  }
  return { version, platforms }
}

async function buildCodexSection(version) {
  const metadata = await fetchJson('https://registry.npmjs.org/@openai/codex')
  const platforms = {}
  for (const { key } of PLATFORMS) {
    const npmVersion = `${version}-${key}`
    const entry = metadata.versions?.[npmVersion]
    if (!entry) throw new Error(`@openai/codex@${npmVersion} not found on npm`)
    platforms[key] = { npmVersion, integrity: entry.dist.integrity }
  }
  return { version, platforms }
}

async function buildNodeSection(version) {
  const shasums = await fetchText(`https://nodejs.org/dist/v${version}/SHASUMS256.txt`)
  const byFile = new Map()
  for (const line of shasums.split('\n')) {
    const match = line.trim().match(/^([0-9a-f]{64})\s+(.+)$/)
    if (match) byFile.set(match[2], match[1])
  }

  const platforms = {}
  for (const { key, nodePlatform, nodeArch, archiveExt, exePath } of PLATFORMS) {
    const archive = `node-v${version}-${nodePlatform}-${nodeArch}.${archiveExt}`
    const sha256 = byFile.get(archive)
    if (!sha256) throw new Error(`${archive} missing from nodejs.org SHASUMS256.txt for v${version}`)
    platforms[key] = { nodePlatform, nodeArch, archiveExt, exePath, sha256 }
  }
  return { version, platforms }
}

async function main() {
  const versions = expectedVersions()
  let previous = null
  try {
    previous = await readFile(outFile, 'utf8')
  } catch {
    // The first successful generation creates the catalog.
  }

  let catalog
  try {
    catalog = {
      _comment: 'GENERATED by scripts/sync-runtime-catalog.mjs — do not edit by hand. Run `npm run sync:runtime-catalog`.',
      claude: await buildClaudeSection(versions.claude),
      codex: await buildCodexSection(versions.codex),
      node: await buildNodeSection(versions.node),
    }
  } catch (error) {
    if (previous) {
      console.warn(`[sync-runtime-catalog] skipped regeneration (offline?): ${error.message || error}`)
      console.warn(`[sync-runtime-catalog] keeping existing ${outFile}`)
      return
    }
    throw error
  }

  const serialized = `${JSON.stringify(catalog, null, 2)}\n`
  if (serialized === previous) {
    console.log(`[sync-runtime-catalog] up to date (claude ${versions.claude}, codex ${versions.codex}, node ${versions.node})`)
    return
  }
  await writeFile(outFile, serialized)
  console.log(`[sync-runtime-catalog] wrote ${outFile} (claude ${versions.claude}, codex ${versions.codex}, node ${versions.node})`)
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isMain) {
  main().catch((error) => {
    console.error('[sync-runtime-catalog] failed:', error.message || error)
    process.exitCode = 1
  })
}

export { buildClaudeSection, buildCodexSection, buildNodeSection, expectedVersions, PLATFORMS, outFile }
